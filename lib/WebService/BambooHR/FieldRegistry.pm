package WebService::BambooHR::FieldRegistry;

use 5.010;
use strict;
use warnings;
use Moo;
use JSON::MaybeXS qw( decode_json encode_json );
use File::Basename qw( dirname );
use File::Path qw( make_path );
use Time::HiRes qw( time );

use WebService::BambooHR::Exception::FieldNotFound;
use WebService::BambooHR::Exception::TableNotFound;
use WebService::BambooHR::Exception::DeprecatedField;
use WebService::BambooHR::Exception::AmbiguousField;

use constant CACHE_FORMAT => 2;    # bump whenever the cached structure changes; old caches are refetched

=head1 NAME

WebService::BambooHR::FieldRegistry - resolve configured field/table keys to BambooHR ids and aliases

=head1 SYNOPSIS

    my $registry = WebService::BambooHR::FieldRegistry->new(
        user_agent => $bamboo,                        # the WebService::BambooHR client
        cache_path => '/var/cache/myapp/fields.json',  # optional: omit to keep the metadata in memory only
    )->load;

    my $f = $registry->lookup_field('Shirt Size');            # { id, alias, column_aliases, name, type, keys }
    my $t = $registry->resolve_table('customEquipment');      # the table alias
    my $c = $registry->lookup_table_field( $t, 'Serial #' );  # { id, alias, name, type }

=head1 DESCRIPTION

BambooHR configuration (custom fields, custom tables) is identified by ids and generated aliases that differ
between accounts. This class turns the labels a person writes in a configuration file into the ids and aliases the
API needs, using the account's own metadata. Its behaviour follows what the API was observed to return (see
F<docs/api-notes.md>):

=over 4

=item * C<GET /v1/meta/fields> is an array of C<< {id, name, type[, alias][, deprecated]} >>. Ids are JSON
numbers for ordinary fields and JSON I<strings> for sub-fields such as C<"1234.6">. B<Display names are not
unique> (two fields may both be called C<Hire Date>), and some aliases are shared too. Lookups therefore never
pick a winner: an ambiguous key raises L<WebService::BambooHR::Exception::AmbiguousField> listing the candidates.

=item * C<GET /v1/meta/tables> is an array of C<< {alias, fields => [ {id, name, alias, type} ]} >>. There is
B<no table display name>: tables are identified by alias only.

=item * Table columns also appear in C</meta/fields>, but there they usually have I<no alias>; the alias is only
in C</meta/tables>. Row data is keyed by the C<meta/tables> column alias, while C<reports/custom> keys a field by
its alias from either source and C<GET employees/{id}?fields=ID> keys it by the id. The registry merges both
so a caller can look a value up under every name it might arrive as (C<column_aliases>, C<keys>).

=item * Aliases are generated by BambooHR (spaces removed, punctuation kept, a numeric suffix on collision), so
they cannot be predicted and must be read back from the API.

=item * B<One id can be listed more than once>, typically when a field was renamed: the same C<id> then appears with
two names and two aliases. All of them are kept and every one resolves to that id; C<name> and C<alias> are the first
listed, C<names> and C<aliases> hold them all, and C<keys> includes every alias.

=item * Display names may carry stray leading, trailing or doubled whitespace. Names are therefore compared
trimmed, whitespace-collapsed and case-folded.

=back

C<GET /v1/hris/custom-fields> is not used: BambooHR's reference lists only OAuth2 credentials for it.

=cut

has 'user_agent' => ( is => 'ro', required => 1 );
# Optional. With no cache_path the metadata lives in memory for the life of the object (two requests per load).
# There is deliberately no default location: a library should not choose a directory in the caller's filesystem.
has 'cache_path' => ( is => 'ro', default => sub { undef } );
has 'cache_ttl'  => ( is => 'ro', default => sub { 86400 } );

has '_fields'    => ( is => 'rw', default => sub { {} } );   # id => { id, name, alias, type, deprecated, column_aliases }
has '_tables'    => ( is => 'rw', default => sub { {} } );   # alias => { alias, fields => [ { id, name, alias, type } ] }
has '_by_alias'  => ( is => 'rw', default => sub { {} } );   # lc(alias) => [ ids ]   (field aliases AND column aliases)
has '_by_name'   => ( is => 'rw', default => sub { {} } );   # lc(name)  => [ ids ]
has '_raw_fields' => ( is => 'rw', default => sub { [] } );  # /meta/fields as normalised, before table columns are merged in (this is what is cached)
has '_loaded_at' => ( is => 'rw', default => sub { 0 } );

=head2 load / refresh

C<load> reads the cache if one is configured and still fresh, otherwise fetches C</meta/fields> and C</meta/tables>.
C<refresh> always fetches. Both return the registry.

=cut

sub load    { my $s = shift; $s->_cache_fresh ? $s->_load_from_cache : $s->_fetch_and_cache; return $s }
sub refresh { my $s = shift; $s->_fetch_and_cache; return $s }

# ---------------------------------------------------------------------------------------------- employee-level fields

=head2 lookup_field( $key )

C<$key> is a numeric id (C<9001>, C<"9100.6">), an alias, or a display name, tried in that order. Returns
C<< { id, name, type, alias, column_aliases, keys } >>; C<keys> is the ordered, de-duplicated list of every
key the value may be returned under (id, field alias, table-column aliases).

Throws FieldNotFound, AmbiguousField or DeprecatedField.

=cut

sub lookup_field {
    my ( $self, $key ) = @_;
    $key = _trim($key);
    my $e;
    if ( $key =~ /^\d+(?:\.\d+)?$/ && ( $e = $self->_fields->{$key} ) ) { }
    else {
        my @by_alias = _uniq( @{ $self->_by_alias->{ lc $key } // [] } );
        my @by_name  = _uniq( @{ $self->_by_name->{ _norm($key) } // [] } );
        my @ids      = @by_alias ? @by_alias : @by_name;    # an alias beats a display name

        $self->_throw( 'FieldNotFound', "no BambooHR field matches '$key' (tried id, alias, display name)", 404, 'Not Found', label => $key )
            unless @ids;
        # when ambiguous, show everything the key could have meant: a bare word like "Comments" is the alias of several
        # table columns *and* the display name of other fields
        $self->_ambiguous( "'$key'", [ map { $self->_fields->{$_} } sort { _id_cmp( $a, $b ) } _uniq( @by_alias, @by_name ) ] ) if @ids > 1;
        $e = $self->_fields->{ $ids[0] };
    }

    $self->_throw( 'DeprecatedField', "field '$key' (id=$e->{id}) is deprecated in BambooHR", 410, 'Gone', label => $key, field_id => $e->{id} )
        if $e->{deprecated};
    return _public($e);
}

=head2 resolve_field( $key )

The field id (a string).

=cut

sub resolve_field { my ( $self, $key ) = @_; return $self->lookup_field($key)->{id} }

# ---------------------------------------------------------------------------------------------- tables

=head2 table_aliases( [ custom_only ] )

Sorted list of table aliases.

=cut

sub table_aliases {
    my ( $self, $custom_only ) = @_;
    return sort grep { !$custom_only || /^custom/ } keys %{ $self->_tables };
}

=head2 lookup_table( $alias )

Exact alias, else a unique case-insensitive match. Returns C<< { alias, fields } >>. Throws TableNotFound, whose
message lists the custom tables that do exist (display names are not available, so aliases are all there is).

=cut

sub lookup_table {
    my ( $self, $key ) = @_;
    $key = _trim($key);
    my $t = $self->_tables->{$key};
    unless ($t) {
        my @m = grep { lc $_ eq lc $key } keys %{ $self->_tables };
        $t = $self->_tables->{ $m[0] } if @m == 1;
    }
    unless ($t) {
        my @c = $self->table_aliases(1);
        $self->_throw( 'TableNotFound',
            "no BambooHR table has alias '$key' (tables are identified by alias, not display name; custom tables: "
              . ( @c ? join( ', ', @c ) : 'none' ) . ')',
            404, 'Not Found', label => $key );
    }
    return { alias => $t->{alias}, fields => [ map { {%$_} } @{ $t->{fields} } ] };
}

=head2 resolve_table( $alias )

The table alias, i.e. the C<{table}> path segment.

=cut

sub resolve_table { my ( $self, $key ) = @_; return $self->lookup_table($key)->{alias} }

=head2 lookup_table_field( $table, $key )

Resolves a column I<within one table> (by id, alias or display name). This is the only reliable way to find a
column, because display names repeat across the tenant. Returns C<< { id, alias, name, type } >>; C<alias> is the
key row data is returned under. Throws TableNotFound, FieldNotFound or AmbiguousField.

=cut

sub lookup_table_field {
    my ( $self, $table, $key ) = @_;
    $key = _trim($key);
    my $t = ref $table eq 'HASH' ? $table : $self->lookup_table($table);
    my @cols = @{ $t->{fields} };

    my @hit = $key =~ /^\d+$/ ? grep { $_->{id} eq $key } @cols : ();
    @hit = grep { defined $_->{alias} && lc $_->{alias} eq lc $key } @cols unless @hit;
    @hit = grep { defined $_->{name}  && _norm( $_->{name} ) eq _norm($key) } @cols unless @hit;

    $self->_throw( 'FieldNotFound', "table '$t->{alias}' has no column matching '$key' (columns: "
          . join( ', ', map { "'$_->{name}'" } @cols ) . ')', 404, 'Not Found', label => $key )
        unless @hit;
    $self->_ambiguous( "'$key' in table '$t->{alias}'", [ sort { _id_cmp( $a->{id}, $b->{id} ) } @hit ] ) if @hit > 1;
    return { %{ $hit[0] } };
}

=head2 resolve_table_field( $table, $key )

The column alias: the key row data is returned under (and the key to write a row with).

=cut

sub resolve_table_field { my ( $self, $table, $key ) = @_; return $self->lookup_table_field( $table, $key )->{alias} }

# ---------------------------------------------------------------------------------------------- internals

sub _trim { my $s = shift // ''; $s =~ s/^\s+|\s+$//g; return $s }

# Display names can carry stray whitespace (a trailing space, doubled interior spaces), so a name typed in a mapping would
# never match an exact comparison. Compare names trimmed, whitespace-collapsed and case-folded. Two names that differ only in
# whitespace become one ambiguous name, which is accurate: they are indistinguishable to a person typing a mapping
# (e.g. 'Plan  - Employer pays' vs 'Plan - Employer pays').
sub _clean { my $s = shift; return $s unless defined $s; $s =~ s/\s+/ /g; $s =~ s/^ | $//g; return $s }
sub _norm  { return lc _clean(shift) }
sub _uniq { my %s; return grep { !$s{$_}++ } @_ }

# ids are "9001" or "9100.6"; sort numerically so output never depends on Perl's hash ordering
sub _id_cmp { my ( $x, $y ) = @_; my @x = split /\./, $x; my @y = split /\./, $y; return ( $x[0] <=> $y[0] ) || ( ( $x[1] // -1 ) <=> ( $y[1] // -1 ) ) }
sub _by_id_order { my ($h) = @_; return map { $h->{$_} } sort { _id_cmp( $a, $b ) } keys %$h }

sub _public {
    my ($e) = @_;
    my @keys = _uniq( grep { defined && length } ( $e->{id}, @{ $e->{aliases} // [] }, @{ $e->{column_aliases} // [] } ) );
    return {
        id => $e->{id}, name => $e->{name}, type => $e->{type}, alias => $e->{alias},
        names => [ @{ $e->{names} // [] } ], aliases => [ @{ $e->{aliases} // [] } ], column_aliases => [ @{ $e->{column_aliases} // [] } ],
        keys  => \@keys,
    };
}

sub _ambiguous {
    my ( $self, $what, $cands ) = @_;
    my $list = join '; ', map { "id $_->{id} ('$_->{name}'" . ( defined $_->{alias} ? ", alias $_->{alias}" : '' ) . ')' } @$cands;
    $self->_throw( 'AmbiguousField', "$what matches " . scalar(@$cands) . " fields: $list. Use the numeric id or the alias in the mapping.",
        409, 'Ambiguous', label => $what, candidates => [ map { {%$_} } @$cands ] );
}

# The base exception's as_string() concatenates method/message/code/reason/filename/line_number, so all must be set.
# Report the first non-internal frame (the public method), as upstream's _get does.
sub _throw {
    my ( $self, $type, $message, $code, $reason, %extra ) = @_;
    my $i = 1;
    $i++ while ( ( caller($i) )[3] // '' ) =~ /::_[A-Za-z_]+$/;
    my @f = caller($i);
    "WebService::BambooHR::Exception::$type"->throw({
        method => $f[3] // __PACKAGE__, message => $message, code => $code, reason => $reason,
        filename => $f[1] // '(unknown)', line_number => $f[2] // 0, %extra,
    });
}

sub _cache_fresh {
    my $self = shift;
    return 0 unless defined $self->cache_path && -f $self->cache_path;
    return ( time - ( stat( $self->cache_path ) )[9] ) < $self->cache_ttl;
}

sub _fetch_and_cache {
    my $self   = shift;
    my $fields = decode_json( $self->user_agent->_get('meta/fields')->{content} );
    my $tables = decode_json( $self->user_agent->_get('meta/tables')->{content} );
    $self->_build( _normalize_fields($fields), _normalize_tables($tables) );
    $self->_loaded_at(time);
    $self->_write_cache;
    return $self;
}

# Strict on purpose: both shapes were observed on a real tenant, and a silent fallback would hide an API change.
sub _normalize_fields {
    my ($raw) = @_;
    die "unexpected /meta/fields response: expected a JSON array of {id,name,type...}\n" unless ref $raw eq 'ARRAY';
    return [ map { {
        id => "$_->{id}", name => _clean( $_->{name} ), type => $_->{type}, alias => $_->{alias}, deprecated => ( $_->{deprecated} ? 1 : 0 ),
    } } grep { ref $_ eq 'HASH' && defined $_->{id} } @$raw ];
}

sub _normalize_tables {
    my ($raw) = @_;
    die "unexpected /meta/tables response: expected a JSON array of {alias, fields:[...]}\n" unless ref $raw eq 'ARRAY';
    my %out;
    for my $t ( grep { ref $_ eq 'HASH' && defined $_->{alias} } @$raw ) {
        $out{ $t->{alias} } = {
            alias  => $t->{alias},
            fields => [ map { { id => "$_->{id}", name => _clean( $_->{name} ), alias => $_->{alias}, type => $_->{type} } }
                        grep { ref $_ eq 'HASH' && defined $_->{id} } @{ $t->{fields} // [] } ],
        };
    }
    return \%out;
}

sub _build {
    my ( $self, $fields, $tables ) = @_;

    # /meta/fields can list one id more than once (a renamed field keeps both its names and aliases). Merge them: the first listed
    # name/alias/type is primary, every name and alias still resolves, and the entry is deprecated only if all of them are.
    my ( %by_id, @order );
    for my $f (@$fields) {
        my $e = $by_id{ $f->{id} };
        unless ($e) {
            $e = $by_id{ $f->{id} } = { id => $f->{id}, name => undef, type => undef, alias => undef, deprecated => 1, names => [], aliases => [], column_aliases => [] };
            push @order, $f->{id};
        }
        $e->{type} //= $f->{type};
        push @{ $e->{names} },   $f->{name}  if defined $f->{name}  && length _clean( $f->{name} );
        push @{ $e->{aliases} }, $f->{alias} if defined $f->{alias} && length $f->{alias};
        $e->{deprecated} = 0 unless $f->{deprecated};
    }
    for my $e ( values %by_id ) {
        $e->{names}   = [ _uniq( @{ $e->{names} } ) ];
        $e->{aliases} = [ _uniq( @{ $e->{aliases} } ) ];
        $e->{name}    = $e->{names}[0];
        $e->{alias}   = $e->{aliases}[0];
    }

    for my $t ( map { $tables->{$_} } sort keys %$tables ) {
        for my $c ( @{ $t->{fields} } ) {
            my $e = $by_id{ $c->{id} } //= { id => $c->{id}, name => $c->{name}, type => $c->{type}, alias => undef, deprecated => 0,
                                              names => [ grep { defined && length } $c->{name} ], aliases => [], column_aliases => [] };
            push @{ $e->{column_aliases} }, $c->{alias} if defined $c->{alias} && !grep { $_ eq $c->{alias} } @{ $e->{aliases} };
        }
    }
    $_->{column_aliases} = [ _uniq( @{ $_->{column_aliases} } ) ] for values %by_id;

    my ( %alias, %name );
    for my $e ( _by_id_order( \%by_id ) ) {
        push @{ $alias{ lc $_ } }, $e->{id} for grep { defined && length } ( @{ $e->{aliases} }, @{ $e->{column_aliases} } );
        push @{ $name{ _norm($_) } }, $e->{id} for @{ $e->{names} };
    }
    $_ = [ _uniq(@$_) ] for values %alias, values %name;
    $self->_raw_fields($fields);
    $self->_fields( \%by_id );
    $self->_tables($tables);
    $self->_by_alias( \%alias );
    $self->_by_name( \%name );
}

sub _load_from_cache {
    my $self = shift;
    open my $fh, '<', $self->cache_path or return $self->_fetch_and_cache;
    local $/; my $json = <$fh>; close $fh;
    my $d = eval { decode_json($json) };
    return $self->_fetch_and_cache if $@ || ref $d ne 'HASH' || ( $d->{format} // 0 ) != CACHE_FORMAT || ref $d->{fields} ne 'ARRAY' || ref $d->{tables} ne 'HASH';
    $self->_build( $d->{fields}, $d->{tables} );
    $self->_loaded_at( $d->{loaded_at} // 0 );
    return $self;
}

sub _write_cache {
    my $self = shift;
    return 1 unless defined $self->cache_path;
    my $dir = dirname( $self->cache_path );
    eval { make_path($dir) } unless -d $dir;    # best effort: an unwritable cache dir must not kill a sync
    my $tmp = $self->cache_path . ".tmp.$$";
    open my $fh, '>', $tmp or return;    # best effort: never fail a sync over the cache
    print {$fh} encode_json({
        format    => CACHE_FORMAT,
        loaded_at => $self->_loaded_at,
        fields    => $self->_raw_fields,
        tables    => $self->_tables,
    });
    close $fh;
    rename $tmp, $self->cache_path;
    return 1;
}

1;
